test('a transfer from another outlet is booked in, and one sent out can be called back', async ({ page }) => {
  await demo(page)
  await go(page, 'Transfer')
  const incoming = page.locator('.order-card').filter({ hasText: 'Dari Cabang Dago (demo)' })
  await incoming.getByRole('button', { name: 'Terima transfer' }).click()
  const receive = page.getByRole('dialog', { name: 'Terima transfer' })
  await receive.getByLabel('Diterima (pcs)').fill('28') // two eggs broke on the way
  await receive.getByRole('button', { name: 'Konfirmasi penerimaan' }).click()
  await expect(page.getByText('Transfer diterima dan masuk stok')).toBeVisible()
  await page.getByRole('button', { name: 'Kirim transfer' }).click()
  const send = page.getByRole('dialog', { name: 'Kirim transfer' })
  await choose(page, send, 'Bahan', 'Telur (pcs)')
  await send.getByLabel(/Jumlah/).fill('10')
  await send.getByRole('button', { name: 'Tambah bahan' }).click()
  await send.getByRole('button', { name: 'Kirim sekarang' }).click()
  const outgoing = page.locator('.order-card').filter({ hasText: 'Ke Cabang Dago (demo)' })
  await expect(outgoing).toContainText('Dalam perjalanan')
  await go(page, 'Stok')
  const eggs = page.locator('.stock-row').filter({ has: page.getByRole('heading', { name: 'Telur', exact: true }) }).locator('.stock-quantity strong')
  await expect(eggs).toHaveText('68') // 50 + 28 received − 10 sent
  await expect(balance(page, 'Beras')).toHaveText('15.000')
  await go(page, 'Transfer')
  await page.getByRole('button', { name: 'Keluar' }).click()
  await outgoing.getByRole('button', { name: 'Batalkan transfer' }).click()
  await page.getByRole('dialog', { name: 'Batalkan transfer' }).getByLabel('Alasan wajib').fill('Kurir tidak datang')
  await page.getByRole('dialog', { name: 'Batalkan transfer' }).getByRole('button', { name: 'Konfirmasi pembatalan' }).click()
  await expect(outgoing).toContainText('Dibatalkan')
  await go(page, 'Stok')
  await expect(eggs).toHaveText('78')
})

test('a batch recipe turns raw stock into a ready item through Produksi', async ({ page }) => {
  await demo(page)
  await go(page, 'Lainnya')
  await page.getByRole('button', { name: 'Daftar bahan' }).click()
  await page.getByRole('button', { name: 'Tambah bahan' }).click()
  const item = page.getByRole('dialog', { name: 'Bahan stok' })
  await item.getByLabel('Nama bahan').fill('Telur balado (porsi)')
  await item.getByLabel(/Dibuat sendiri dari bahan lain/).check()
  await choose(page, item, 'Bahan per batch', 'Telur (pcs)')
  await item.getByLabel('Jumlah satuan dasar').fill('10')
  await item.getByRole('button', { name: 'Tambah bahan produksi' }).click()
  await item.getByLabel(/Hasil per batch/).fill('10')
  await item.getByRole('button', { name: 'Simpan bahan' }).click()
  await expect(page.getByText('Bahan tersimpan')).toBeVisible()
  await go(page, 'Produksi')
  const row = page.locator('.stock-row').filter({ hasText: 'Telur balado (porsi)' })
  await expect(row).toContainText('1 batch: Telur 10 pcs → 10 pcs')
  await expect(row).toContainText('harga sebagian bahan belum tercatat') // demo eggs have no purchase price yet
  await row.getByRole('button', { name: 'Catat produksi' }).click()
  const run = page.getByRole('dialog', { name: /Produksi Telur balado/ })
  await run.getByLabel('Jumlah batch').fill('2')
  await expect(run.getByLabel(/Hasil sebenarnya/)).toHaveValue('20')
  await run.getByLabel(/Hasil sebenarnya/).fill('19') // one cracked
  await run.getByRole('button', { name: 'Simpan produksi' }).click()
  await expect(page.getByText('Produksi tercatat; stok diperbarui')).toBeVisible()
  await expect(row.locator('.stock-quantity strong')).toHaveText('19')
  await expect(page.locator('.history-list')).toContainText('Produksi Telur balado (porsi)')
  await go(page, 'Stok')
  const eggs = page.locator('.stock-row').filter({ has: page.getByRole('heading', { name: 'Telur', exact: true }) })
  await expect(eggs.locator('.stock-quantity strong')).toHaveText('30') // 50 demo eggs − 2 batches × 10
  // Once eggs have a purchase price, each batch is costed from it.
  await go(page, 'Pembelian')
  await page.getByRole('button', { name: 'Buat PO' }).click()
  const po = page.getByRole('dialog', { name: 'PO baru' })
  await po.getByLabel('Pemasok').fill('Pasar')
  await choose(page, po, 'Bahan', 'Telur (pcs)')
  await po.getByLabel('Jumlah').fill('10')
  await po.getByLabel('Harga total baris').fill('20000')
  await po.getByRole('button', { name: 'Tambah ke PO' }).click()
  await po.getByRole('button', { name: 'Simpan PO' }).click()
  await page.locator('.order-card').filter({ hasText: 'Pasar' }).getByRole('button', { name: 'Terima kiriman' }).click()
  await page.getByRole('dialog', { name: 'Terima kiriman' }).getByRole('button', { name: 'Konfirmasi penerimaan' }).click()
  await go(page, 'Produksi')
  await expect(row).toContainText('Biaya per batch ≈ Rp20.000 · Rp2.000/pcs')
})

