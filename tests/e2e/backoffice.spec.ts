import { test, expect, demo, go, openShift, addItem, sell, balance, cart } from './meja'
import type { Page } from '@playwright/test'
const choose = async (page: Page, scope: ReturnType<Page['getByRole']>, label: string, option: string) => {
  // A combobox is named by its label plus the chosen value, so match the label at the start only.
  await scope.getByRole('combobox', { name: new RegExp(`^${label}`) }).click()
  await page.getByRole('option', { name: option }).click()
}

test('a PO to a saved supplier arrives in two deliveries, is paid in parts, and goes out by WhatsApp', async ({ page }) => {
  await demo(page)
  await go(page, 'Pembelian')
  await page.getByRole('button', { name: 'Pemasok' }).click()
  await page.getByRole('button', { name: 'Tambah pemasok' }).click()
  const supplier = page.getByRole('dialog', { name: 'Pemasok' })
  await supplier.getByLabel('Nama pemasok').fill('CV Beras Makmur')
  await supplier.getByLabel(/Nomor WhatsApp/).fill('0812-3456-7890')
  await supplier.getByRole('button', { name: 'Simpan pemasok' }).click()
  await expect(page.locator('.admin-row').filter({ hasText: 'CV Beras Makmur' })).toContainText('0812-3456-7890')
  await page.getByRole('button', { name: 'Menunggu kiriman' }).click()
  await page.getByRole('button', { name: 'Buat PO' }).click()
  const po = page.getByRole('dialog', { name: 'PO baru' })
  await po.getByLabel('Pemasok').fill('CV Beras Makmur')
  await choose(page, po, 'Bahan', 'Beras (g)')
  await po.getByLabel('Jumlah').fill('10')
  await choose(page, po, 'Satuan', 'kg (1.000 g)')
  await po.getByLabel('Harga total baris').fill('150000')
  await po.getByRole('button', { name: 'Tambah ke PO' }).click()
  await po.getByRole('button', { name: 'Simpan PO' }).click()
  const card = page.locator('.order-card').filter({ hasText: 'CV Beras Makmur' })
  await expect(card).toContainText('Dipesan')
  await card.getByRole('button', { name: /Cetak atau kirim/ }).click()
  const doc = page.getByRole('dialog', { name: /^PO-/ })
  await expect(doc.locator('#print-area')).toContainText('PURCHASE ORDER')
  await expect(doc.getByRole('link', { name: 'Kirim WhatsApp' })).toHaveAttribute('href', /^https:\/\/wa\.me\/6281234567890\?text=PURCHASE%20ORDER/)
  await page.keyboard.press('Escape')
  // First delivery: 6 of the 10 kg, paid now outside the drawer.
  await card.getByRole('button', { name: 'Terima kiriman' }).click()
  let receive = page.getByRole('dialog', { name: 'Terima kiriman' })
  await receive.getByLabel('Beras (g)').fill('6000')
  await receive.getByLabel('Harga total').fill('90000')
  await receive.getByRole('button', { name: 'Konfirmasi penerimaan' }).click()
  await expect(page.getByText('Kiriman diterima dan masuk stok')).toBeVisible()
  await expect(card).toContainText('Sebagian diterima')
  await expect(card).toContainText('Beras 6.000/10.000 g')
  // Second delivery: the rest, on credit; it completes the PO.
  await card.getByRole('button', { name: 'Terima kiriman' }).click()
  receive = page.getByRole('dialog', { name: 'Terima kiriman' })
  await expect(receive.getByLabel('Beras (g)')).toHaveValue('4000')
  await choose(page, receive, 'Pembayaran kiriman ini', 'Belum dibayar (tempo)')
  await receive.getByRole('button', { name: 'Konfirmasi penerimaan' }).click()
  await page.getByRole('button', { name: 'Belum dibayar' }).click()
  await expect(card).toContainText('Selesai · belum lunas')
  await expect(card).toContainText('sisa Rp60.000')
  await card.getByRole('button', { name: 'Bayar' }).click()
  const pay = page.getByRole('dialog', { name: 'Bayar pemasok' })
  await pay.getByLabel('Jumlah dibayar').fill('40000')
  await pay.getByRole('button', { name: 'Simpan pembayaran' }).click()
  await expect(card).toContainText('sisa Rp20.000')
  await go(page, 'Stok')
  await expect(balance(page, 'Beras')).toHaveText('20.000') // 10 kg demo stock + 6 + 4 kg
})

