import { test, expect, demo, addItem, cart, go, prints } from './meja'
// Cashless pilot PRD (2026-11-13): card or QRIS on an EDC, the receipt prints by itself, compliments,
// voiding one item with a PIN, and a close that matches each EDC's settlement slip after a stock count.
test('a cashless day: EDC payment, compliment, item void, count, then the EDC settlement', async ({ page }) => {
  await demo(page)
  await go(page, 'Lainnya')
  await page.getByRole('button', { name: 'Restoran' }).click()
  await page.getByLabel(/Tablet dapur & bar/).uncheck()
  await page.getByLabel(/Tanpa tunai/).check()
  await page.getByLabel(/Mesin EDC/).fill('BCA, BRI')
  await page.getByLabel(/Anggaran compliment/).fill('3000000')
  await page.getByRole('button', { name: 'Simpan pengaturan' }).click()
  await expect(page.getByText('Pengaturan tersimpan')).toBeVisible()
  await go(page, 'Kasir')
  // No float: the cashier checks the EDCs and opens.
  await page.getByRole('button', { name: /Buka sif untuk melayani/ }).click()
  await expect(page.getByLabel(/Modal kas awal/)).toHaveCount(0)
  await page.getByRole('button', { name: 'Buka sif sekarang' }).click()
  await expect(page.getByText('Sif terbuka', { exact: true })).toBeVisible()
  // A card sale on EDC BRI with the approval code; the receipt prints without a tap.
  await addItem(page, 'Nasi goreng kampung')
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: /Lanjut pembayaran/ }).click()
  const pay = page.getByRole('dialog', { name: 'Terima pembayaran' })
  await expect(pay.getByRole('button', { name: 'Tunai' })).toHaveCount(0)
  await pay.getByRole('button', { name: 'EDC BRI' }).click()
  await pay.getByLabel(/Kode approval/).fill('412093')
  const before = await prints(page)
  await pay.getByRole('button', { name: /Konfirmasi: dibayar di EDC BRI/ }).click()
  const receipt = page.getByRole('dialog', { name: 'Pembayaran tercatat' })
  await expect(receipt).toContainText('Kartu, EDC BRI')
  await expect(receipt).toContainText('412093')
  await expect.poll(() => prints(page)).toBe(before + 1)
  await page.keyboard.press('Escape')
  // Owner's family: free, no payment sheet.
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: 'Compliment' }).click()
  await cart(page).getByRole('button', { name: /Keluarga pemilik/ }).click()
  await cart(page).getByLabel('Nama penerima compliment').fill('Rino')
  await cart(page).getByRole('button', { name: /Simpan compliment/ }).click()
  await expect(page.getByRole('dialog', { name: 'Pembayaran tercatat' })).toContainText('Compliment')
  await page.keyboard.press('Escape')
  // Void the tea off the paid card order; the owner approves on the spot, so no PIN.
  await go(page, 'Pesanan')
  await page.getByRole('button', { name: /^Lunas/ }).click()
  await page.getByLabel('Cari pesanan').fill('412093')
  await page.locator('.order-card').first().getByRole('button', { name: 'Detail' }).click()
  const detail = page.getByRole('dialog')
  await detail.getByRole('button', { name: 'Batalkan item' }).last().click()
  await detail.getByLabel(/Alasan wajib/).fill('Salah menu')
  await detail.getByRole('button', { name: 'Konfirmasi pembatalan item' }).click()
  await expect(page.getByText(/Item dibatalkan/)).toBeVisible()
  // Close: count first, then each EDC's slip. BRI took the rice only now.
  await go(page, 'Sif & kas')
  await expect(page.getByRole('heading', { name: 'Tutup sif', level: 1 })).toBeVisible()
  await expect(page.locator('.metric').filter({ hasText: 'Staf Rp' })).toContainText('Rp6.000')
  await page.getByLabel('Slip EDC BCA').fill('0')
  await page.getByLabel('Slip EDC BRI').fill('25000')
  await expect(page.getByRole('button', { name: 'Tutup sif' })).toBeDisabled()
  await go(page, 'Hitung stok')
  await page.getByRole('button', { name: 'Mulai menghitung' }).click()
  const count = page.getByRole('dialog')
  await count.getByLabel('Teh (porsi)').fill('40')
  await count.getByRole('button', { name: 'Kirim untuk ditinjau' }).click()
  await go(page, 'Sif & kas')
  await page.getByLabel('Slip EDC BCA').fill('0')
  await page.getByLabel('Slip EDC BRI').fill('25000')
  await expect(page.locator('.settle-row').filter({ hasText: 'BRI' })).toContainText('Cocok')
  await page.getByRole('button', { name: 'Tutup sif' }).click()
  await expect(page.getByText(/Sif ditutup/)).toBeVisible()
})
