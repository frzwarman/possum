import { test, expect, demo, openShift, addItem, cart, go, balance } from './meja'
// Pilot PRD: no bar or kitchen tablets yet. The cashier tells them, stock moves when the order is paid,
// the cashier keeps stock between orders, and the till never opens the manager screens during a shift.
test('without station tablets, paying sends the order and moves stock in one tap', async ({ page }) => {
  await demo(page)
  await go(page, 'Lainnya')
  await page.getByRole('button', { name: 'Restoran' }).click()
  await page.getByLabel(/Tablet dapur & bar/).uncheck()
  await page.getByRole('button', { name: 'Simpan pengaturan' }).click()
  await expect(page.getByText('Pengaturan tersimpan')).toBeVisible()
  await expect(page.locator('.sidebar').getByRole('link', { name: 'Stasiun' })).toHaveCount(0)
  await go(page, 'Kasir')
  await openShift(page)
  await addItem(page, 'Es teh manis')
  await expect(cart(page).getByRole('button', { name: /Ke stasiun/ })).toHaveCount(0)
  await expect(cart(page).getByText('Stok berkurang saat pembayaran dicatat.')).toBeVisible()
  await cart(page).getByRole('button', { name: /Lanjut pembayaran/ }).click()
  const pay = page.getByRole('dialog', { name: 'Terima pembayaran' })
  await pay.getByRole('button', { name: /Catat pembayaran/ }).click()
  await expect(page.getByRole('dialog', { name: 'Pembayaran tercatat' })).toBeVisible()
  await page.keyboard.press('Escape')
  // The owner is on the till with a shift open: stock work yes, back office no.
  await expect(page.locator('.sidebar').getByRole('link', { name: 'Hari ini' })).toHaveCount(0)
  await go(page, 'Stok')
  await expect(balance(page, 'Teh (porsi)')).toHaveText('49')
  await page.locator('.stock-row').filter({ hasText: 'Teh (porsi)' }).getByRole('button', { name: 'Catat stok' }).click()
  const dialog = page.getByRole('dialog', { name: 'Teh (porsi)' })
  await expect(dialog.getByRole('combobox', { name: /^Jenis pencatatan/ })).toContainText('Terbuang')
  await page.keyboard.press('Escape')
  await go(page, 'Hitung stok')
  await expect(page.getByRole('heading', { name: 'Hitung stok', level: 1 })).toBeVisible()
})
test('the cashier has a Stock tab: low and sold-out menu, waste, batches and counts', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Coba sebagai' }).click()
  await page.getByRole('option', { name: 'Kasir' }).click()
  await page.getByRole('button', { name: 'Jelajahi demo lokal' }).click()
  const nav = page.locator('.sidebar')
  for (const name of ['Stok', 'Produksi', 'Hitung stok']) await expect(nav.getByRole('link', { name, exact: true })).toBeVisible()
  for (const name of ['Laporan', 'Penjualan', 'Pembelian', 'Hari ini']) await expect(nav.getByRole('link', { name, exact: true })).toHaveCount(0)
  await go(page, 'Stok')
  await page.locator('.stock-row').filter({ hasText: 'Telur' }).first().getByRole('button', { name: 'Catat stok' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Jumlah', { exact: true }).fill('1')
  await dialog.getByRole('button', { name: 'Jatuh' }).click()
  await dialog.getByRole('button', { name: 'Simpan pergerakan' }).click()
  await expect(page.getByText('Pergerakan stok tersimpan')).toBeVisible()
})
