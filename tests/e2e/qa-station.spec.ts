import { test, expect, demo, openShift, addItem, cart, go } from './meja'
// QA 2026-11-25, cluster station: STN-11 (undo a bump), STN-13 (age), STN-16 (Siap in Pesanan), STN-15 (cancel notice).
async function sendTea(page: import('@playwright/test').Page, label?: string) {
  await demo(page)
  await openShift(page)
  if (label) await cart(page).getByLabel(/Nomor pager/).fill(label)
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: /Ke stasiun/ }).click()
  await expect(cart(page).getByText(/Dikirim · bar/)).toBeVisible()
}
test('a bump can be taken back, a new ticket is 0 minutes old, and Pesanan shows the order ready', async ({ page }) => {
  await sendTea(page)
  await go(page, 'Stasiun')
  await page.getByRole('button', { name: 'Bar' }).click()
  const ticket = page.locator('.ticket')
  await expect(ticket.locator('.ticket-age')).toHaveText('0 mnt')
  await ticket.getByRole('button', { name: 'Siap' }).click()
  await expect(ticket).toHaveCount(0)
  await page.getByRole('button', { name: 'Urungkan' }).click()
  await expect(ticket).toHaveCount(1)
  await ticket.getByRole('button', { name: 'Siap' }).click()
  await expect(page.getByText('Tiket siap; kasir bisa memanggil pager')).toBeVisible({ timeout: 15000 })
  await go(page, 'Pesanan')
  await expect(page.locator('.order-row').filter({ hasText: 'Pager 1' }).locator('.order-status.good', { hasText: 'Siap' })).toBeVisible()
})
test('an order voided after it reached the bar shows as a cancel notice on the board', async ({ page }) => {
  await sendTea(page, 'Meja 9')
  await go(page, 'Pesanan')
  await page.locator('.order-row').filter({ hasText: 'Meja 9' }).click()
  await page.getByRole('button', { name: 'Batalkan pesanan' }).click()
  await page.getByLabel('Alasan wajib').fill('Pelanggan pergi')
  await page.getByRole('button', { name: /Konfirmasi pembatalan/ }).click()
  await expect(page.getByText('Koreksi tersimpan di perangkat')).toBeVisible()
  await go(page, 'Stasiun')
  await page.getByRole('button', { name: 'Bar' }).click()
  const card = page.locator('.ticket.late').filter({ hasText: 'Meja 9' })
  await expect(card).toContainText('Dibatalkan')
  await expect(card).toContainText('Es teh manis')
  await card.getByRole('button', { name: 'Mengerti' }).click()
  await expect(card).toHaveCount(0)
})
