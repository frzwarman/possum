import { test, expect, openShift, addItem, cart, go, sell } from './meja'
import type { Page } from '@playwright/test'
// Each demo role is its own sandbox on this device, like separate staff accounts.
async function demoAs(page: Page, role: 'Pemilik · super admin' | 'Manajer · admin' | 'Kasir') {
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Coba sebagai' }).click()
  await page.getByRole('option', { name: role }).click()
  await page.getByRole('button', { name: 'Jelajahi demo lokal' }).click()
  await expect(page.getByRole('heading', { name: 'Kasir', level: 1 })).toBeVisible()
}
async function approveWith(page: Page, approver: string, pin = '123456') {
  const dialog = page.getByRole('dialog', { name: 'Persetujuan manajer' })
  await dialog.getByRole('combobox', { name: 'Disetujui oleh' }).click()
  await page.getByRole('option', { name: approver }).click()
  await dialog.getByLabel('PIN persetujuan').fill(pin)
  await dialog.getByRole('button', { name: 'Setujui' }).click()
  return dialog
}

test('a cashier sees only the till: no stock, no sales figures, and counts the drawer blind', async ({ page }) => {
  await demoAs(page, 'Kasir')
  const nav = page.locator('.sidebar')
  await expect(nav.getByRole('link', { name: 'Stok' })).toHaveCount(0)
  for (const name of ['Laporan', 'Penjualan', 'Katering', 'Pembelian', 'Produksi', 'Transfer']) await expect(nav.getByRole('link', { name })).toHaveCount(0)
  await openShift(page)
  await addItem(page, 'Es teh manis')
  await sell(page)
  await page.keyboard.press('Escape')
  await go(page, 'Sif & kas')
  await expect(page.getByRole('heading', { name: 'Sif & kas' })).toBeVisible()
  await expect(page.getByText(/Penjualan tercatat|Kas yang seharusnya|Penjualan tunai bersih/)).toHaveCount(0)
  // Cash out of the drawer needs a manager's PIN.
  await page.getByRole('button', { name: 'Catat kas masuk / keluar' }).click()
  const cash = page.getByRole('dialog', { name: 'Mutasi laci kas' })
  await cash.getByLabel('Jumlah').fill('2000')
  await cash.getByLabel('Alasan').fill('Es batu')
  await cash.getByRole('button', { name: 'Simpan mutasi' }).click()
  await approveWith(page, 'Manajer Demo')
  await expect(page.getByText('Mutasi kas tersimpan')).toBeVisible()
  await page.getByRole('button', { name: 'Tutup sif' }).click()
  const closing = page.getByRole('dialog', { name: 'Tutup sif' })
  await expect(closing.getByText('Kas yang seharusnya')).toHaveCount(0)
  await expect(closing.locator('.payment-total, .bill-total')).toHaveCount(0) // no expected amount, no variance
  await closing.getByLabel(/Uang tunai yang dihitung/).fill('204000')
  await closing.getByRole('button', { name: 'Konfirmasi tutup sif' }).click()
  await expect(closing).toBeHidden()
  await expect(page.locator('.history-list')).toContainText(/Dihitung Rp\s*204\.000/)
  await expect(page.locator('.history-list')).not.toContainText('Selisih')
  await page.goto('/inventory')
  await expect(page.getByRole('heading', { name: 'Kasir', level: 1 })).toBeVisible()
})

test("a cashier's discount and void wait for a manager's PIN, and the approver is recorded", async ({ page }) => {
  await demoAs(page, 'Kasir')
  await openShift(page)
  await cart(page).getByLabel(/Meja \/ nama pesanan/).fill('Meja 4')
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: 'Tambah diskon' }).click()
  const discount = page.getByRole('dialog', { name: 'Diskon manajer' })
  await discount.getByLabel('Potongan').fill('1000')
  await discount.getByLabel('Alasan').fill('Langganan')
  await discount.getByRole('button', { name: 'Terapkan diskon' }).click()
  const approval = await approveWith(page, 'Pemilik Demo', '000000')
  await expect(approval.getByRole('alert')).toHaveText('PIN salah')
  await expect(cart(page).locator('.bill-total')).toContainText(/Rp\s*6\.000/)
  await approveWith(page, 'Pemilik Demo')
  await expect(approval).toBeHidden()
  await expect(cart(page).locator('.bill-total')).toContainText(/Rp\s*5\.000/)
  await cart(page).getByRole('button', { name: /Ke dapur/ }).click()
  await expect(cart(page).getByText(/Dikirim ke dapur/)).toBeVisible()
  await go(page, 'Pesanan')
  await page.locator('.order-card').filter({ hasText: 'Meja 4' }).getByRole('button', { name: 'Detail' }).click()
  const detail = page.getByRole('dialog', { name: 'Meja 4' })
  await expect(detail).toContainText('Diskon Rp1.000: Langganan · disetujui Pemilik Demo')
  await detail.getByRole('button', { name: 'Batalkan pesanan' }).click()
  await detail.getByLabel('Alasan wajib').fill('Pelanggan pergi')
  await detail.getByRole('button', { name: /Konfirmasi pembatalan/ }).click()
  await approveWith(page, 'Manajer Demo')
  await expect(page.getByText('Koreksi tersimpan di perangkat')).toBeVisible()
  await page.getByRole('button', { name: 'Semua' }).click()
  await page.locator('.order-card').filter({ hasText: 'Meja 4' }).getByRole('button', { name: 'Detail' }).click()
  await expect(page.getByRole('dialog', { name: 'Meja 4' })).toContainText('Dibatalkan: Pelanggan pergi · disetujui Manajer Demo')
})

test('the owner sees every correction with who asked and who approved it', async ({ page }) => {
  await demoAs(page, 'Pemilik · super admin')
  await openShift(page)
  await cart(page).getByLabel(/Meja \/ nama pesanan/).fill('Meja 8')
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: 'Tambah diskon' }).click()
  const discount = page.getByRole('dialog', { name: 'Diskon manajer' })
  await discount.getByLabel('Potongan').fill('1000')
  await discount.getByLabel('Alasan').fill('Teman pemilik')
  await discount.getByRole('button', { name: 'Terapkan diskon' }).click()
  await expect(page.getByRole('dialog', { name: 'Persetujuan manajer' })).toHaveCount(0) // the owner approves their own
  await sell(page)
  await page.keyboard.press('Escape')
  await go(page, 'Laporan')
  const audit = page.locator('.panel').filter({ hasText: 'Koreksi & persetujuan' })
  await expect(audit).toContainText('Diskon Rp1.000 · Meja 8')
  await expect(audit).toContainText('Teman pemilik · kasir Pemilik Demo · disetujui Pemilik Demo')
})
