import { test, expect, demo, openShift, addItem, cart, go } from './meja'
// F2: one send splits the ticket by station; each station marks its own lines ready.
test('the bar sees the drink, the kitchen the food, and the order is ready once both have served', async ({ page }) => {
  await demo(page)
  await openShift(page)
  await expect(cart(page).getByLabel(/Nomor pager/)).toHaveValue('Pager 1')
  await addItem(page, 'Nasi goreng kampung')
  await addItem(page, 'Es teh manis')
  await cart(page).getByRole('button', { name: /Ke stasiun/ }).click()
  await expect(cart(page).getByText(/Dikirim · dapur/)).toBeVisible()
  await expect(cart(page).getByText(/Dikirim · bar/)).toBeVisible()
  await go(page, 'Stasiun')
  await page.getByRole('button', { name: 'Bar' }).click()
  const ticket = page.locator('.ticket')
  await expect(ticket).toHaveCount(1)
  await expect(ticket).toContainText('Pager 1')
  await expect(ticket).toContainText('Es teh manis')
  await expect(ticket).not.toContainText('Nasi goreng')
  await ticket.getByRole('button', { name: 'Siap' }).click()
  await expect(page.locator('.ticket')).toHaveCount(0)
  await go(page, 'Pesanan')
  await expect(page.locator('.order-card').filter({ hasText: 'Pager 1' })).toContainText('Sedang disiapkan')
  await go(page, 'Stasiun')
  await page.getByRole('button', { name: 'Dapur' }).click()
  await expect(page.locator('.ticket')).toContainText('Nasi goreng kampung')
  await page.locator('.ticket').getByRole('button', { name: 'Siap' }).click()
  await go(page, 'Pesanan')
  await expect(page.locator('.order-card').filter({ hasText: 'Pager 1' })).toContainText('Siap disajikan')
})
test('crew log waste from the station in three taps', async ({ page }) => {
  await demo(page)
  await go(page, 'Stasiun')
  await page.getByRole('button', { name: 'Catat buang' }).click()
  const dialog = page.getByRole('dialog', { name: 'Catat buang' })
  await dialog.getByRole('combobox', { name: /^Bahan/ }).click()
  await page.getByRole('option', { name: 'Telur (pcs)' }).click()
  await dialog.getByLabel('Jumlah').fill('2')
  await dialog.getByRole('button', { name: 'Jatuh' }).click()
  await dialog.getByRole('button', { name: 'Simpan' }).click()
  await expect(page.getByText('Telur dicatat terbuang')).toBeVisible()
  await go(page, 'Stok')
  await expect(page.locator('.stock-row').filter({ has: page.getByRole('heading', { name: 'Telur', exact: true }) }).locator('.stock-quantity strong')).toHaveText('48')
})
